/**
 * Generates group `index.ts` files from a manifest + filesystem scan.
 *
 * Each animation group needs a boilerplate index.ts that wires up Vite's
 * `import.meta.glob` calls (which must be literal at the call site). This
 * script generates those files from a single manifest, eliminating drift
 * and enforcing a canonical structure.
 *
 * Usage:
 *   node scripts/codegen/generate-group-indexes.mjs           # generate / overwrite
 *   node scripts/codegen/generate-group-indexes.mjs --check    # verify freshness (CI)
 */

