// ── Template ─────────────────────────────────────────────────────────────────

function generateGroupIndex(group, { hasSharedCss }) {
  const lines = []

  lines.push('/**')
  lines.push(' * @generated by scripts/codegen/generate-group-indexes.mjs \u2014 DO NOT EDIT')
  lines.push(' */')

  if (hasSharedCss) {
    lines.push("import './shared.css'")
  }

  if (group.extraCssImports) {
    for (const imp of group.extraCssImports) {
      lines.push(`import '${imp}'`)
    }
  }

  lines.push("import type { AnimationMetadata, GroupMetadata } from '@/types/animation'")
  lines.push("import { buildGroupExport } from '@/lib/groupBuilder'")
  lines.push('')
  lines.push(
    '// Side-effect: load framer-variant non-module CSS (layout only \u2014 animation CSS banned by lint)'
  )
  lines.push("import.meta.glob(['./framer/*.css', '!./framer/*.module.css'], { eager: true })")
  lines.push('')
  lines.push('const metadata: GroupMetadata = {')
  lines.push(`  id: '${group.id}',`)
  lines.push(`  title: '${escapeSingleQuote(group.title)}',`)
  lines.push(`  demo: '${escapeSingleQuote(group.demo)}',`)
  lines.push('}')
  lines.push('')
  lines.push('export const groupExport = buildGroupExport(')
  lines.push('  metadata,')
  lines.push("  import.meta.glob<Record<string, unknown>>('./framer/*.tsx'),")
  lines.push(
    "  import.meta.glob<{ metadata: AnimationMetadata }>('./framer/*.meta.ts', { eager: true }),"
  )
  lines.push("  import.meta.glob<Record<string, unknown>>('./css/*.tsx'),")
  lines.push(
    "  import.meta.glob<{ metadata: AnimationMetadata }>('./css/*.meta.ts', { eager: true }),"
  )
  lines.push('  {')
  lines.push("    framerTsx: import.meta.glob<string>('./framer/*.{ts,tsx}', {")
  lines.push("      query: '?raw',")
  lines.push("      import: 'default',")
  lines.push('    }),')
  lines.push(
    "    framerCss: import.meta.glob<string>('./framer/*.css', { query: '?raw', import: 'default' }),"
  )
  lines.push(
    "    cssTsx: import.meta.glob<string>('./css/*.{ts,tsx}', { query: '?raw', import: 'default' }),"
  )
  lines.push(
    "    cssCss: import.meta.glob<string>('./css/*.css', { query: '?raw', import: 'default' }),"
  )
  lines.push(
    "    shared: import.meta.glob<string>('./*.{ts,tsx}', { query: '?raw', import: 'default' }),"
  )
  lines.push('  }')
  lines.push(')')
  lines.push('')

  return lines.join('\n')
}

function escapeSingleQuote(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
}

// ── Main ─────────────────────────────────────────────────────────────────────

const isCheck = process.argv.includes('--check')
let stale = 0
let written = 0
let errors = 0

for (const group of GROUPS) {
  const groupDir = resolve(COMPONENTS, group.category, group.id)
  const indexPath = resolve(groupDir, 'index.ts')
  const rel = relative(ROOT, indexPath)

  if (!existsSync(groupDir)) {
    console.error(`ERROR: group directory missing: ${rel}`)
    errors++
    continue
  }

  if (!existsSync(resolve(groupDir, 'framer')) || !existsSync(resolve(groupDir, 'css'))) {
    console.error(`ERROR: ${rel} — missing framer/ or css/ subdirectory`)
    errors++
    continue
  }

  const hasSharedCss = existsSync(resolve(groupDir, 'shared.css'))
  const expected = generateGroupIndex(group, { hasSharedCss })

  if (isCheck) {
    const actual = existsSync(indexPath) ? readFileSync(indexPath, 'utf8') : ''
    if (actual !== expected) {
      console.error(`STALE: ${rel}`)
      stale++
    }
  } else {
    writeFileSync(indexPath, expected, 'utf8')
    written++
  }
}

if (errors > 0) {
  console.error(`\n${errors} error(s) — fix manifest or filesystem before continuing.`)
  process.exit(1)
}

if (isCheck) {
  if (stale > 0) {
    console.error(`\n${stale} file(s) stale. Run: pnpm run generate:groups`)
    process.exit(1)
  }
  console.log(`All ${GROUPS.length} group index files are up to date.`)
} else {
  console.log(`Generated ${written} group index files.`)
}
